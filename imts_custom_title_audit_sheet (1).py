# --- CONFIGURATION ---
BASE_URL = "https://imtsinstitute.com/"
MAX_PAGES = 15  # Isko aap pure website ke liye badha sakte hain (e.g., 100)

def crawl_site(base_url, max_pages=15):
    print(f"🚀 Crawling shuru ho gayi hai: {base_url}")
    visited = set()
    to_visit = [base_url]
    scraped_urls = []

    domain = urlparse(base_url).netloc

    while to_visit and len(visited) < max_pages:
        current_url = to_visit.pop(0)
        if current_url in visited:
            continue

        try:
            headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'}
            response = requests.get(current_url, headers=headers, timeout=10)
            visited.add(current_url)

            if response.status_code == 200:
                scraped_urls.append(current_url)
                soup = BeautifulSoup(response.text, 'html.parser')

                # Internal links dhoondhna
                for link in soup.find_all('a', href=True):
                    href = link['href']
                    full_url = urljoin(current_url, href)
                    parsed_url = urlparse(full_url)

                    # Sirf same domain ki links accept karna aur fragments (#) hatana
                    clean_url = f"{parsed_url.scheme}://{parsed_url.netloc}{parsed_url.path}"
                    if parsed_url.netloc == domain and clean_url not in visited and clean_url not in to_visit:
                        to_visit.append(clean_url)
        except Exception as e:
            print(f"⚠️ Error crawling {current_url}: {e}")

    return scraped_urls

