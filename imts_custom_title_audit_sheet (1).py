def get_all_pages(base_url, max_pages=15):
    """Website ke internal pages ko crawl karne ke liye function"""
    print(f"🔍 crawling shuru ho rahi hai: {base_url}")
    target_domain = urlparse(base_url).netloc
    urls_to_visit = [base_url]
    visited_urls = set()

    while urls_to_visit and len(visited_urls) < max_pages:
        current_url = urls_to_visit.pop(0)
        if current_url in visited_urls:
            continue

        try:
            headers = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'}
            response = requests.get(current_url, headers=headers, timeout=10)
            visited_urls.add(current_url)

            soup = BeautifulSoup(response.text, 'html.parser')
            for link in soup.find_all('a', href=True):
                href = link['href']
                full_url = urljoin(current_url, href)
                parsed_url = urlparse(full_url)

                # Sirf internal links ko pick karne ke liye checks
                if parsed_url.netloc == target_domain and full_url not in visited_urls and full_url not in urls_to_visit:
                    # Static files ya login endpoints ko skip karne ke liye
                    if not any(ext in parsed_url.path for ext in ['.pdf', '.jpg', '.png', '.zip', 'logout']):
                        urls_to_visit.append(full_url)
        except Exception as e:
            visited_urls.add(current_url)

    return list(visited_urls)

